                                        <script>
                                            (function() {
                                                const track = document.getElementById('cvsTrack');
                                                const dotsBox = document.getElementById('cvsDots');
                                                const prev = document.querySelector('.cvs-arrow-prev');
                                                const next = document.querySelector('.cvs-arrow-next');
                                                const cards = track.querySelectorAll('.cvs-card');
                                                let index = 0;

                                                // Pengaturan autoplay (hanya mobile)
                                                const AUTOPLAY_DELAY = 3000; // jeda antar geser (ms)
                                                const RESUME_DELAY = 5000; // jeda setelah user menyentuh/klik (ms)
                                                const MOBILE_MAX = 768; // harus sama dengan breakpoint mobile di CSS
                                                let autoTimer = null;
                                                let resumeTimer = null;

                                                // Harus sama dengan breakpoint di CSS
                                                function perView() {
                                                    const w = window.innerWidth;
                                                    if (w <= 560) return 1;
                                                    if (w <= 900) return 2;
                                                    return 3;
                                                }

                                                function maxIndex() {
                                                    return Math.max(0, cards.length - perView());
                                                }

                                                function render() {
                                                    const gap = parseFloat(getComputedStyle(track).columnGap) || 0;
                                                    const step = cards[0].offsetWidth + gap;
                                                    track.style.transform = 'translateX(' + (-index * step) + 'px)';
                                                    prev.disabled = index === 0;
                                                    next.disabled = index >= maxIndex();
                                                    dotsBox.querySelectorAll('.cvs-dot').forEach(function(d, i) {
                                                        d.classList.toggle('is-active', i === index);
                                                    });
                                                }

                                                function buildDots() {
                                                    dotsBox.innerHTML = '';
                                                    for (let i = 0; i <= maxIndex(); i++) {
                                                        const d = document.createElement('button');
                                                        d.className = 'cvs-dot';
                                                        d.setAttribute('aria-label', 'Slide ' + (i + 1));
                                                        d.addEventListener('click', function() {
                                                            index = i;
                                                            render();
                                                            restartAutoplayLater();
                                                        });
                                                        dotsBox.appendChild(d);
                                                    }
                                                }

                                                // ---------- Autoplay (mobile saja) ----------
                                                function isMobile() {
                                                    return window.innerWidth <= MOBILE_MAX;
                                                }

                                                function stopAutoplay() {
                                                    clearInterval(autoTimer);
                                                    autoTimer = null;
                                                }

                                                function startAutoplay() {
                                                    stopAutoplay();
                                                    if (!isMobile()) return;
                                                    autoTimer = setInterval(function() {
                                                        // Geser ke kanan; setelah card terakhir, kembali ke card pertama
                                                        index = index >= maxIndex() ? 0 : index + 1;
                                                        render();
                                                    }, AUTOPLAY_DELAY);
                                                }

                                                // Jeda sebentar setelah user berinteraksi, lalu lanjut lagi
                                                function restartAutoplayLater() {
                                                    stopAutoplay();
                                                    clearTimeout(resumeTimer);
                                                    resumeTimer = setTimeout(startAutoplay, RESUME_DELAY);
                                                }

                                                prev.addEventListener('click', function() {
                                                    index = Math.max(0, index - 1);
                                                    render();
                                                    restartAutoplayLater();
                                                });
                                                next.addEventListener('click', function() {
                                                    index = Math.min(maxIndex(), index + 1);
                                                    render();
                                                    restartAutoplayLater();
                                                });

                                                // Swipe untuk mobile
                                                let startX = 0;
                                                track.addEventListener('touchstart', function(e) {
                                                    startX = e.touches[0].clientX;
                                                    stopAutoplay(); // berhenti selama jari menyentuh
                                                    clearTimeout(resumeTimer);
                                                }, {
                                                    passive: true
                                                });
                                                track.addEventListener('touchend', function(e) {
                                                    const diff = e.changedTouches[0].clientX - startX;
                                                    if (Math.abs(diff) > 40) {
                                                        index = diff < 0 ? Math.min(maxIndex(), index + 1) : Math.max(0, index - 1);
                                                        render();
                                                    }
                                                    restartAutoplayLater();
                                                });

                                                // Hemat baterai: berhenti saat tab/halaman tidak terlihat
                                                document.addEventListener('visibilitychange', function() {
                                                    if (document.hidden) {
                                                        stopAutoplay();
                                                    } else {
                                                        startAutoplay();
                                                    }
                                                });

                                                window.addEventListener('resize', function() {
                                                    index = Math.min(index, maxIndex());
                                                    buildDots();
                                                    render();
                                                    startAutoplay(); // aktif/nonaktif otomatis sesuai lebar layar
                                                });

                                                buildDots();
                                                render();
                                                startAutoplay();
                                            })();
                                        </script>
