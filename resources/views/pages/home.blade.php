    <script>
        document.addEventListener("DOMContentLoaded", function() {

            const counters = document.querySelectorAll(".counter");

            const animateCounter = (counter) => {

                const target = parseInt(
                    counter.textContent.replace(/,/g, ""),
                    10
                );

                const duration = 3000; // 2 detik terasa lebih natural daripada 4 detik

                const startTime = performance.now();

                // Easing lebih halus: easeInOutCubic
                const easeInOutCubic = (t) =>
                    t < 0.5 ?
                    4 * t * t * t :
                    1 - Math.pow(-2 * t + 2, 3) / 2;

                const updateCounter = (currentTime) => {

                    const elapsed = currentTime - startTime;
                    const progress = Math.min(elapsed / duration, 1);

                    const eased = easeInOutCubic(progress);

                    const currentNumber = Math.round(target * eased);

                    counter.textContent = currentNumber.toLocaleString("en-US");

                    if (progress < 1) {
                        requestAnimationFrame(updateCounter);
                    } else {
                        counter.textContent = target.toLocaleString("en-US");
                    }
                };

                requestAnimationFrame(updateCounter);
            };

            const observer = new IntersectionObserver(
                (entries, observer) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            animateCounter(entry.target);
                            observer.unobserve(entry.target);
                        }
                    });
                }, {
                    threshold: 0.5
                }
            );

            counters.forEach(counter => {
                observer.observe(counter);
            });

        });
    </script>
